// Package fileio holds the low-level file operations the key manager builds on:
// a size-capped read, a durable create-and-write, a directory sync and a
// read that tolerates a missing or non-regular entry.
package fileio

import (
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"runtime"
	"syscall"

	"github.com/Glyndor/authcore/internal/keymanager/layout"
)

// ReadCapped reads up to layout.MaxKeyFileSize bytes from path and returns an error
// if the file is larger. It replaces os.ReadFile at every key-loading site.
func ReadCapped(path string) ([]byte, error) {
	// #nosec G304 -- path derived from trusted config.KeysDir and fixed filename, not user input
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()

	// Stat first so an obviously oversized file is rejected before any read.
	if fi, err := f.Stat(); err == nil && fi.Size() > layout.MaxKeyFileSize {
		return nil, fmt.Errorf("file %q is %d bytes, exceeds %d-byte cap", path, fi.Size(), layout.MaxKeyFileSize)
	}

	// Read at most layout.MaxKeyFileSize+1 bytes. If the +1 byte actually arrives,
	// the file streams more than the stat reported (symlink race, pipe-like
	// path) and the loader refuses it.
	data, err := io.ReadAll(io.LimitReader(f, layout.MaxKeyFileSize+1))
	if err != nil {
		return nil, err
	}
	if len(data) > layout.MaxKeyFileSize {
		return nil, fmt.Errorf("file %q exceeds %d-byte cap", path, layout.MaxKeyFileSize)
	}
	return data, nil
}

// SyncDir flushes a directory's metadata to disk.
//
// On Windows, fs.Sync on a directory handle does not flush directory metadata
// and can return an access error, so there is nothing useful to do. Return
// nil immediately rather than translating a Windows-specific error.
//
// On filesystems that do not implement directory sync (some FUSE mounts, some
// network filesystems) the kernel returns errors.ErrUnsupported or
// syscall.EINVAL on the Sync call; both are reported as nil because the
// alternative is to refuse to start on a filesystem the operator chose.
// Failing to open the directory is a real error and is returned verbatim.
func SyncDir(path string) error {
	if runtime.GOOS == "windows" {
		return nil
	}
	// #nosec G304 -- path is KeysDir or a staging directory inside it; both come from the trusted config and a fixed layout
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer func() { _ = f.Close() }()
	return tolerateUnsupportedSync(f.Sync())
}

// tolerateUnsupportedSync maps the answer a filesystem gives when it cannot
// sync a directory to success and passes every other error through.
func tolerateUnsupportedSync(err error) error {
	if errors.Is(err, errors.ErrUnsupported) || errors.Is(err, syscall.EINVAL) {
		return nil
	}
	return err
}

// WriteKeyFile creates path, writes data, fsyncs and closes it. Used by the
// staging path so the staged entries themselves survive a machine crash even
// before they are hard-linked into KeysDir.
func WriteKeyFile(path string, data []byte, perm os.FileMode) error {
	// #nosec G304 -- path is KeysDir or a staging directory inside it; names are fixed or generated by stagingDirName
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, perm)
	if err != nil {
		return err
	}
	return writeSyncClose(f, data)
}

// syncWriteCloser is the part of *os.File that writeSyncClose uses, so a test
// can make each step fail.
type syncWriteCloser interface {
	Write(p []byte) (int, error)
	Sync() error
	Close() error
}

// writeSyncClose writes data to f, fsyncs it and closes it, closing f on every
// path.
func writeSyncClose(f syncWriteCloser, data []byte) error {
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		_ = f.Close()
		return err
	}
	return f.Close()
}

// FileBytesIfExists returns the bytes of path when it exists and is a regular
// file. A symlink resolves to its target, so a regular-file target returns its
// bytes; a non-regular target returns ("", false, nil) so the caller skips it.
func FileBytesIfExists(path string) ([]byte, bool, error) {
	fi, err := os.Stat(path)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, false, nil
		}
		return nil, false, err
	}
	if !fi.Mode().IsRegular() {
		return nil, false, nil
	}
	data, err := ReadCapped(path)
	if err != nil {
		return nil, false, err
	}
	return data, true, nil
}
